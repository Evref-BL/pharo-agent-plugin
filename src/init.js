import fs from "node:fs";
import path from "node:path";
import { templateDirectory as mcpTemplateDirectory } from "@evref-bl/pharo-mcp";
import { guideForHost, hostList } from "./hosts.js";
import {
  createProjectConfig,
  enclosingProjectRoot,
  pluginDirectory,
  projectConfigFileName,
  projectConfigPath,
} from "./project.js";

// The host guide is the user's file, so our few lines are fenced off inside
// it. `pharo.AGENTS.md` is ours whole, and needs no fence: one sentence says
// where it came from, which a reader can act on and init can recognize.
const managedStart = "<!-- pharo-agent:begin -->";
const managedEnd = "<!-- pharo-agent:end -->";
const generatedBy = "Generated by `pharo-agent init`";

function copyDirectory(source, target) {
  for (const entry of fs.readdirSync(source, { withFileTypes: true })) {
    const sourcePath = path.join(source, entry.name);
    const targetPath = path.join(target, entry.name);
    if (sourcePath.endsWith(`${path.sep}agents${path.sep}openai.yaml`)) continue;
    if (entry.isDirectory()) {
      copyDirectory(sourcePath, targetPath);
    } else {
      fs.mkdirSync(target, { recursive: true });
      fs.copyFileSync(sourcePath, targetPath);
    }
  }
}

function assertManagedBlockCanBeUpdated(filePath) {
  const current = fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : "";
  const start = current.indexOf(managedStart);
  const end = current.indexOf(managedEnd);
  if ((start === -1) !== (end === -1) || (end !== -1 && end < start)) {
    throw new Error(`Cannot update incomplete pharo-agent block in ${filePath}`);
  }
}

function updateManagedBlock(filePath, content) {
  assertManagedBlockCanBeUpdated(filePath);
  const current = fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : "";
  const start = current.indexOf(managedStart);
  const end = current.indexOf(managedEnd);

  const block = `${managedStart}\n${content}\n${managedEnd}\n`;
  const updated = start === -1
    ? `${current}${current && !current.endsWith("\n") ? "\n" : ""}${block}`
    : `${current.slice(0, start)}${block}${current.slice(end + managedEnd.length).replace(/^\n?/, "")}`;
  fs.writeFileSync(filePath, updated);
}

function writeIfMissing(filePath, content) {
  if (!fs.existsSync(filePath)) {
    fs.writeFileSync(filePath, content);
  }
}

function assertGeneratedGuideCanBeUpdated(filePath) {
  if (!fs.existsSync(filePath)) return;
  const content = fs.readFileSync(filePath, "utf8");
  if (!content.includes(generatedBy) && !content.includes(managedStart)) {
    throw new Error(`Refusing to replace user-owned ${filePath}`);
  }
}

function guidance() {
  return `# Pharo work\n\nWhen the task uses Pharo, read \`pharo.AGENTS.md\` before acting.\n`;
}

// MCP ships the references and skills, so which one answers what is its to
// state. Repeating the list here went stale the first time a template was
// renamed, and sent readers to files that are no longer installed. Only the
// paths differ, because init copies the two template directories under
// `.pharo-agent`.
function pharoRouting() {
  const templates = mcpTemplateDirectory();
  const guide = fs.readFileSync(path.join(templates, "pharo.AGENTS.md"), "utf8");
  const guidance = guide.indexOf("## Read First");
  if (guidance === -1) {
    throw new Error("The MCP agent guide no longer opens its guidance with ## Read First");
  }
  const routing = guide
    .slice(guidance)
    .replaceAll("pharo-references/", ".pharo-agent/references/")
    .replaceAll("pharo-skills/", ".pharo-agent/skills/")
    .replaceAll("skills/", ".pharo-agent/skills/")
    .replaceAll(".pharo-agent/.pharo-agent/", ".pharo-agent/")
    .trimEnd();
  assertRoutingResolves(routing, templates);
  return routing;
}

// A path the routing names must be a file MCP actually provides, so a renamed
// template stops init here rather than pointing a reader at nothing.
function assertRoutingResolves(routing, templates) {
  const directoryNames = { references: "pharo-references", skills: "pharo-skills" };
  for (const [target, directory, relative] of routing.matchAll(
    /\.pharo-agent\/(references|skills)\/([\w./-]+\.md)/g,
  )) {
    if (!fs.existsSync(path.join(templates, directoryNames[directory], relative))) {
      throw new Error(`The MCP agent guide names ${target}, which no template provides`);
    }
  }
}

function pharoGuide() {
  return `# Pharo project guide

${generatedBy}. Edits here are replaced the next time it
runs: re-run it after upgrading the plugin, and keep your own instructions
elsewhere.

## Images

\`plexus.json\` declares this workspace's images. With the plugin, use the
\`image_*\` tools; otherwise:

\`\`\`sh
pharo-agent image templates
pharo-agent image add <id> --template '<template name>'
pharo-agent image start <id>
\`\`\`

The first image declared is the default, the main line. An image takes one
writer, and making one takes seconds: add a new one for each new subject or
parallel agent rather than share one, named like a branch
(\`pretty-print-formatter\`, not \`p15\`). A running image may be another
session's. Stop an image and remove its declaration when its subject is done.

## Tools

With the plugin, an image's tools are MCP tools. Otherwise call one with
\`pharo-agent pharo <tool> [arguments-json] [--image <id>]\`, or serve them
with \`pharo-agent mcp\`. An image lists its common tools; \`tool_search\` and
\`tool_get\` find the rest. On macOS with fuse-t, \`image start\` also mounts
the source under \`.pharo-agent/mounts\`.

${pharoRouting()}
`;
}

function resolveInitProjectRoot(cwd) {
  const projectRoot = path.resolve(cwd);
  if (fs.existsSync(projectConfigPath(projectRoot))) {
    return { projectRoot, createdProjectConfig: false };
  }

  const enclosing = enclosingProjectRoot(projectRoot);
  if (enclosing) {
    throw new Error(
      `${projectRoot} is inside the PLexus project at ${enclosing}. `
        + `Initialize that project root, or remove its ${projectConfigFileName}.`,
    );
  }

  return { projectRoot, createdProjectConfig: true };
}

/** @param {{ host: string, mountRoot?: string, cwd?: string }} options */
export function initialize({ host, mountRoot, cwd = process.cwd() }) {
  const guideName = guideForHost(host);
  if (!guideName) {
    throw new Error(`--host must be ${hostList()}`);
  }

  const { projectRoot, createdProjectConfig } = resolveInitProjectRoot(cwd);
  const directory = pluginDirectory(projectRoot);
  const configPath = path.join(directory, "config.json");
  const pharoGuidePath = path.join(projectRoot, "pharo.AGENTS.md");
  assertGeneratedGuideCanBeUpdated(pharoGuidePath);
  assertManagedBlockCanBeUpdated(path.join(projectRoot, guideName));
  if (createdProjectConfig) {
    createProjectConfig(projectRoot);
  }
  fs.mkdirSync(directory, { recursive: true });
  if (!fs.existsSync(configPath) || mountRoot !== undefined) {
    fs.writeFileSync(
      configPath,
      `${JSON.stringify({ mountRoot: mountRoot ?? ".pharo-agent/mounts" }, null, 2)}\n`,
    );
  }
  writeIfMissing(path.join(directory, ".gitignore"), "mounts/\nruntime/\n");
  fs.writeFileSync(pharoGuidePath, pharoGuide());
  const templates = mcpTemplateDirectory();
  copyDirectory(path.join(templates, "pharo-references"), path.join(directory, "references"));
  copyDirectory(path.join(templates, "pharo-skills"), path.join(directory, "skills"));
  updateManagedBlock(path.join(projectRoot, guideName), guidance());

  return { projectRoot, guideName, createdProjectConfig };
}
